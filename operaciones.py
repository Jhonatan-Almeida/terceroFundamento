num = int(input('Ingrese un Numero: '))
num1 = int(input('Ingrese Otro Numero: '))

suma = num + num1
print(f'El Resultado de la Suma: {suma}')
resta = num1 - num
print(f'El Resultado de la Resta: {resta}')
multiplicacion = num * num1
print(f'El Resultado de la Multiplicacion: {multiplicacion}')
division = num1 / num
print(f'El Resultado de la División: {division}')
resto = num1 % num
print(f'El Resultado del Resto: {resto}')
exponente = num ** 2
print(f'El Resultado del Exponente: {exponente}')